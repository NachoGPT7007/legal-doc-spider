# -*- coding: utf-8 -*-
"""
===============================================================================
 spider 包 —— 爬虫的「引擎舱」
===============================================================================
 这个文件夹（包）里放着爬虫的全部核心零件，每个 .py 文件负责一件事：

   fetcher.py   抓取区：负责「把网页从互联网下载回来」
   parser.py    解析区：负责「从一堆 HTML 里找出真正的正文」
   cleaner.py   清洗区：负责「把正文里的杂质、重复、垃圾行去掉」
   exporter.py  输出区：负责「把结果写成 CSV / txt / JSON 文件」
   crawler.py   调度区：负责「指挥上面四个区，按顺序、按限速地干活」

 为什么要把 5 个小文件放在一个包里，而不是写成一个巨型 .py？
   1. 出问题时好定位 —— 抓不下来是 fetcher 的事，抽不准是 parser 的事
   2. 改一个区不会碰到另一个区 —— 降低「改 A 坏 B」的风险
   3. 以后要升级（比如换成浏览器引擎去抓 JS 网站），只需要动 fetcher 一个文件

 __init__.py 这个文件本身的作用：
   Python 靠它的存在来判断「spider 是一个包（package）」，从而支持
   from spider.parser import extract_article 这样的导入写法。
   它里面的 __all__ 列表声明了「这个包对外提供哪些零件」。
===============================================================================
"""

# __all__ 是一个字符串列表，规定了 `from spider import *` 时会导出哪些名字。
# 它的实际作用：给别人（以及未来的你）一份「这个包的公开接口清单」。
__all__ = ["fetcher", "parser", "cleaner", "exporter", "crawler"]

# 版本号：以后代码有较大改动时手动加一，方便判断你手上是哪一版。
__version__ = "1.0.0"
